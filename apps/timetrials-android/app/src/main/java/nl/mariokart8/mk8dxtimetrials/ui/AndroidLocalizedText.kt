@Composable
internal fun androidLocalizedPresentation(value: String): String {
    val language = LocalAndroidProductLanguage.current
    return if (language == AndroidProductLanguage.DUTCH) {
        AndroidDutchUiCopy.translate(AndroidDutchPresentationCatalog.translate(value))
    } else {
        androidCatalogPresentation(language, value)
    }
}

/**
 * Rendered English in a catalog language (roadmap LANGUAGES_15 B, the web's catalogPresentation): the whole
 * text from the catalog, exactly or by message template, then its game names; English and Dutch pass unchanged.
 */
internal fun androidCatalogPresentation(language: AndroidProductLanguage, value: String): String {
    if (!language.usesCatalog || value.isBlank()) return value
    val trimmed = value.trim()
    val translated = AndroidProductCatalog.replaceGameNames(language.code, AndroidProductCatalog.translate(language.code, trimmed) ?: trimmed)
    if (translated == trimmed) return value
    val start = value.indexOf(trimmed)
    return value.substring(0, start) + translated + value.substring(start + trimmed.length)
}

