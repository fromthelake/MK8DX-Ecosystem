import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

// Design-system contract (IMPLEMENTATION_PLAN §3 Phase 1.7–1.8): the token adapters are generated and
// current, the final legacy stylesheet is retired, and the CSS budget/lint gate holds.
const repo = new URL("../../../", import.meta.url);
const read = (path: string): string => readFileSync(new URL(path, repo), "utf8");
const run = (script: string): string => execFileSync(process.execPath, [script, "--check"], {
  cwd: repo, encoding: "utf8", windowsHide: true,
});

describe("design-system contract", () => {
  it("keeps the generated token adapters in sync with packages/design-tokens", () => {
    expect(() => run("packages/design-tokens/generate.mjs")).not.toThrow();
  });

  it("keeps the web's validation module identical to packages/time-trial-rules", () => {
    // POST_A_TIME §4: ONE validation implementation for web and PWA. The web has no bundler, so the
    // canonical module is generated into src; this gate is what stops that copy drifting, and what
    // makes "no second validator" a checked fact rather than a promise.
    expect(() => run("tooling/design-system/sync-time-trial-rules.mjs")).not.toThrow();
  });

  it("passes the CSS budget and lint gate", () => {
    expect(run("tooling/design-system/css-metrics.mjs")).toContain("CSS gate passed");
  });

  it("has no legacy product stylesheet after Phase 17", () => {
    const html = read("apps/timetrials-web/index.html");
    expect(html).not.toContain("manual-entry.css");
    expect(html).not.toContain("product-page.css");
    expect(read("apps/timetrials-web/styles/ds-workflows.css"))
      .toMatch(/@layer legacy, tokens, base, components;\s*@layer components \{/u);
    expect(read("apps/timetrials-web/styles/ds-workflows.css")).not.toContain("page-shell--");
    expect(read("apps/timetrials-web/styles/ds-tokens.css")).toContain("@layer legacy, tokens, base, components;");
  });

  it("loads the complete design system on every product page", () => {
    const html = read("apps/timetrials-web/index.html");
    for (const sheet of ["ds-tokens.css", "ds-fonts.css", "ds-base.css", "ds-workflows.css", "ds-components.css"]) {
      expect(html).toContain(`./styles/${sheet}`);
    }
    expect(html.indexOf("ds-workflows.css")).toBeLessThan(html.indexOf("ds-components.css"));
    expect(read("apps/timetrials-web/src/main.ts")).not.toMatch(/from "\.\/ds-gallery\.js"/u);
  });

  it("paints the chosen appearance before the stylesheets, with no inline script", () => {
    // ADR-0205 §3: a blocking same-origin head script. The CSP is `script-src 'self'`, so an inline
    // theme script is impossible; a deferred or module script would run after the first paint and
    // produce exactly the flash this prevents.
    const html = read("apps/timetrials-web/index.html");
    expect(html).toContain('<script src="./styles/ds-appearance-boot.js"></script>');
    expect(html.indexOf("ds-appearance-boot.js")).toBeLessThan(html.indexOf("ds-tokens.css"));
    expect(html).not.toMatch(/<script(?![^>]*\ssrc=)/u);
    const boot = read("apps/timetrials-web/styles/ds-appearance-boot.js");
    expect(boot).toContain("data-appearance-choice");
    expect(boot).toMatch(/GENERATED by packages\/design-tokens\/generate\.mjs/u);
    // It must never throw: a blocked storage area is normal, not an error.
    expect(boot).toContain("catch (error)");
  });

  it("resolves System, Light and Dark from one generated token source", () => {
    const tokens = read("apps/timetrials-web/styles/ds-tokens.css");
    expect(tokens).toContain('[data-appearance-choice="light"]');
    expect(tokens).toMatch(/@media \(prefers-color-scheme: light\) \{\s*:root\[data-appearance-choice="system"\]/u);
    // High contrast and forced colours come from the OS and are never a stored choice.
    expect(tokens).toContain("@media (prefers-contrast: more)");
    expect(read("apps/timetrials-web/src/appearance.ts")).not.toMatch(/#[0-9a-fA-F]{6}/u);
  });

  it("declares the same page colour in the manifest and the document", () => {
    const manifest = JSON.parse(read("apps/timetrials-web/manifest.webmanifest")) as
      Record<string, unknown>;
    const html = read("apps/timetrials-web/index.html");
    const meta = /<meta name="theme-color" content="([^"]+)">/u.exec(html)?.[1];
    expect(meta).toBeDefined();
    expect(manifest["theme_color"]).toBe(meta);
    expect(manifest["background_color"]).toBe(meta);
    expect(read("apps/timetrials-web/styles/ds-tokens.css"))
      .toContain(`--ds-surface-app: ${String(meta)};`);
  });

  it("installs the current shell with canonical any and maskable icons", () => {
    const manifest = JSON.parse(read("apps/timetrials-web/manifest.webmanifest")) as
      { name?: string; display?: string; orientation?: string; icons?: readonly Record<string, string>[] };
    expect(manifest.name).toBe("MK8DX Time Trials");
    expect(manifest.display).toBe("standalone");
    expect(manifest.orientation).toBe("any");
    expect(manifest.icons?.map((icon) => `${icon.sizes}:${icon.purpose}`)).toEqual([
      "192x192:any", "512x512:any", "192x192:maskable", "512x512:maskable",
    ]);
    const html = read("apps/timetrials-web/index.html");
    expect(html).toContain("viewport-fit=cover");
    expect(html).toContain('<meta name="mobile-web-app-capable" content="yes">');
    expect(html).toContain('<meta name="apple-mobile-web-app-capable" content="yes">');
    const worker = read("apps/timetrials-web/sw.js");
    expect(worker).not.toContain("manual-entry.css");
    for (const icon of manifest.icons ?? []) {
      expect(worker).toContain(icon["src"]);
    }
  });

  it("keeps the isolated scanner installable without forcing landscape or root-scoped icons", () => {
    const config = read("apps/timetrials-scanner-web/vite.config.ts");
    expect(config).not.toMatch(/orientation\s*:/u);
    expect(config).toContain("`${basePath}icons/icon-192.png`");
    expect(config).toContain("`${basePath}icons/icon-maskable-512.png`");
    const html = read("apps/timetrials-scanner-web/index.html");
    expect(html).toContain("%BASE_URL%icons/icon-192.png");
    expect(html).toContain("viewport-fit=cover");
  });
});
