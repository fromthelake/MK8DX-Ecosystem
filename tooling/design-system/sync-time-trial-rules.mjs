// One validation implementation, delivered to the web app (POST_A_TIME_ARCHITECTURE §4).
//
//   node tooling/design-system/sync-time-trial-rules.mjs            write the generated module
//   node tooling/design-system/sync-time-trial-rules.mjs --check    fail if it has drifted
//
// The web application is built by `tsc` alone and served as plain ES modules: there is no bundler
// that could reach outside `apps/timetrials-web/src`. So the canonical module
// `packages/time-trial-rules/src/index.ts` and the EN/NL message catalogue `rules.json` are copied
// verbatim into one generated source file, exactly as the Dutch presentation catalogue and the track
// catalogue already are. The copy is byte-checked by the design-system contract test, so there is
// still only ONE validation implementation for web/PWA: a second one cannot exist without this gate
// failing.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const sourceFile = join(repo, "packages/time-trial-rules/src/index.ts");
const rulesFile = join(repo, "packages/time-trial-rules/rules.json");
const targetFile = join(repo, "apps/timetrials-web/src/time-trial-rules.generated.ts");
const NEWLINE = String.fromCharCode(10);

export function render() {
  const source = readFileSync(sourceFile, "utf8").replace(/\r\n/g, NEWLINE);
  const rules = JSON.parse(readFileSync(rulesFile, "utf8"));
  const messages = Object.entries(rules.messages).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = [
    "// GENERATED by tooling/design-system/sync-time-trial-rules.mjs. Do not edit.",
    "//",
    "// Sources (the canonical validation, POST_A_TIME_ARCHITECTURE §4 and time-trial-rules/SPEC.md):",
    "//   packages/time-trial-rules/src/index.ts   - the implementation, copied verbatim below",
    "//   packages/time-trial-rules/rules.json     - the EN/NL messages and the server-reason map",
    "//",
    "// The web app has no bundler, so the module is delivered here rather than imported across the",
    "// repository. The design-system contract test re-runs the generator with --check, so this copy",
    "// cannot drift from the package the Kotlin mirror and the server runner are held to.",
    "",
    source.trimEnd(),
    "",
    "// ---------------------------------------------------------------- generated message catalogue",
    "",
    `export const RULES_CATALOGUE_VERSION = ${JSON.stringify(rules.rulesVersion)};`,
    "",
    "export type RuleMessageLanguage = \"en\" | \"nl\";",
    "",
    "/** Every message key in rules.json, in both product languages. */",
    "export const RULE_MESSAGES: Readonly<Record<string, Readonly<Record<RuleMessageLanguage, string>>>> = {",
    ...messages.map(([key, value]) =>
      `  ${JSON.stringify(key)}: { en: ${JSON.stringify(value.en)}, nl: ${JSON.stringify(value.nl)} },`),
    "};",
    "",
    "/** The coarse reason the server answers with for a rule, or null where the server is silent. */",
    "export const RULE_SERVER_REASON: Readonly<Record<RuleId, string | null>> = {",
    ...rules.rules.map((rule) =>
      `  ${JSON.stringify(rule.id)}: ${JSON.stringify(rule.serverReason ?? null)},`),
    "};",
    "",
    "/** The field-level sentence for a validation error, in the viewer's language. */",
    "export function ruleMessage(error: RuleError, language: RuleMessageLanguage): string {",
    "  const template = RULE_MESSAGES[error.messageKey]?.[language];",
    "  return template === undefined ? \"\" : formatMessage(template, error.params);",
    "}",
    "",
  ];
  return lines.join(NEWLINE);
}

const rendered = render();
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(targetFile, "utf8").replace(/\r\n/g, NEWLINE); } catch { current = ""; }
  if (current !== rendered) {
    console.error("time-trial-rules drift: apps/timetrials-web/src/time-trial-rules.generated.ts is not the package's module. Re-run tooling/design-system/sync-time-trial-rules.mjs.");
    process.exit(1);
  }
  console.log("time-trial-rules in sync");
} else {
  writeFileSync(targetFile, rendered);
  console.log("written:", targetFile);
}
