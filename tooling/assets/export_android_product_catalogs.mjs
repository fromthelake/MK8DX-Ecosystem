#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [loadoutInput, benchmarkInput, loadoutOutput, benchmarkOutput] =
  process.argv.slice(2).map((value) => resolve(value));
if ([loadoutInput, benchmarkInput, loadoutOutput, benchmarkOutput]
  .some((value) => value === undefined)) {
  throw new Error(
    "usage: export_android_product_catalogs.mjs <loadout.ts> <benchmarks.ts> " +
    "<AndroidLoadoutCatalog.kt> <AndroidBenchmarkCatalog.kt>",
  );
}

const loadoutSource = readFileSync(loadoutInput, "utf8");
const benchmarkSource = readFileSync(benchmarkInput, "utf8");
const hash = (value) => createHash("sha256").update(value).digest("hex");
const kotlinString = (value) => JSON.stringify(value)
  .replaceAll("$", "\\$");

const statKeys = [
  "speedLand", "speedWater", "speedAntiGravity", "speedGliding",
  "acceleration", "weight", "handlingLand", "handlingWater",
  "handlingAntiGravity", "handlingGliding", "traction", "miniTurbo",
  "invincibility",
];
const categories = [
  ["CHARACTER", "character"],
  ["BODY", "body"],
  ["TIRE", "tire"],
  ["GLIDER", "glider"],
];
const loadoutRows = [];
for (const [constant, category] of categories) {
  const section = loadoutSource.match(new RegExp(
    `export const ${constant}_PARTS:[\\s\\S]*?= \\[([\\s\\S]*?)\\n\\];`,
  ));
  if (section === null) {
    throw new Error(`missing ${constant}_PARTS`);
  }
  const entries = [...section[1].matchAll(
    /\{ id: "([^"]+)", name: "([^"]+)",\s*iconPath: "([^"]+)",\s*stats: (\{[^}]+\}) \}/g,
  )];
  if (entries.length === 0) {
    throw new Error(`empty ${constant}_PARTS`);
  }
  entries.forEach((entry) => {
    const sourceAssetIndex = entry[3].match(/\/(\d+)_/)?.[1];
    if (sourceAssetIndex === undefined) {
      throw new Error(`loadout icon has no source asset index: ${entry[3]}`);
    }
    const stats = JSON.parse(entry[4]);
    loadoutRows.push({
      category,
      sourceAssetIndex: Number(sourceAssetIndex),
      id: entry[1],
      name: entry[2],
      stats: statKeys.map((key) => stats[key] ?? 0),
    });
  });
}

const loadoutKotlin = `// Generated by tooling/assets/export_android_product_catalogs.mjs.
// Source SHA-256: ${hash(loadoutSource)}
package nl.mariokart8.mk8dxtimetrials.builds

internal enum class AndroidBuildPartCategory(val assetFolder: String) {
    CHARACTER("character"), BODY("body"), TIRE("tire"), GLIDER("glider")
}

internal data class AndroidBuildPart(
    val category: AndroidBuildPartCategory,
    val sourceAssetIndex: Int,
    val id: String,
    val name: String,
    val stats: DoubleArray,
    val assetOverride: String? = null,
) {
    val assetPath: String
        get() = assetOverride ?: "private-product/img/${"$"}{category.assetFolder}/${"$"}sourceAssetIndex.png"
}

internal object AndroidLoadoutCatalog {
    const val SOURCE_SHA256 = "${hash(loadoutSource)}"
    val statKeys = listOf(${statKeys.map(kotlinString).join(", ")})
    val parts = listOf(
${loadoutRows.map((row) => `        AndroidBuildPart(AndroidBuildPartCategory.${row.category.toUpperCase()}, ${row.sourceAssetIndex}, ${kotlinString(row.id)}, ${kotlinString(row.name)}, doubleArrayOf(${row.stats.join(", ")}))`).join(",\n")}
    )
    fun parts(category: AndroidBuildPartCategory): List<AndroidBuildPart> =
        parts.filter { it.category == category }

    fun find(id: String?): AndroidBuildPart? = parts.firstOrNull { it.id == id }
}
`;

const benchmarkArray = benchmarkSource.match(
  /const BENCHMARKS:[\s\S]*?= (\[[\s\S]*?\n\]);/,
);
if (benchmarkArray === null) {
  throw new Error("missing BENCHMARKS");
}
const benchmarks = JSON.parse(benchmarkArray[1]);
// The combo and the per-lap readings travel only when the record has them (ADR-0212 fills the
// rest at run time from LiveTrial's ghost readings).
const kotlinList = (values, suffix = "") => `listOf(${values.map((value) => `${value}${suffix}`).join(", ")})`;
const benchmarkExtras = (row) => {
  const parts = ["characterId", "bodyId", "tireId", "gliderId"].map((key) => row.loadout?.[key]);
  const extras = [];
  if (parts.every((part) => typeof part === "string")) {
    extras.push(`loadout = listOf(${parts.map(kotlinString).join(", ")})`);
  }
  if (Array.isArray(row.lapTimesMs)) { extras.push(`lapTimesMs = ${kotlinList(row.lapTimesMs, "L")}`); }
  if (Array.isArray(row.mushroomsPerLap)) { extras.push(`mushroomsPerLap = ${kotlinList(row.mushroomsPerLap)}`); }
  if (Array.isArray(row.coinsPerLap)) { extras.push(`coinsPerLap = ${kotlinList(row.coinsPerLap)}`); }
  return extras.length === 0 ? "" : `, ${extras.join(", ")}`;
};
const benchmarkKotlin = `// Generated by tooling/assets/export_android_product_catalogs.mjs.
// Source SHA-256: ${hash(benchmarkSource)}
package nl.mariokart8.mk8dxtimetrials.track

internal enum class AndroidBenchmarkKind { WORLD_RECORD, NINTENDO_STAFF }

internal data class AndroidTrackBenchmark(
    val kind: AndroidBenchmarkKind,
    val trackId: String,
    val mode: Int,
    val name: String,
    val timeMs: Long,
    val countryId: String?,
    /** Character, body, tire and glider ids in that order, when the record names them. */
    val loadout: List<String>? = null,
    val lapTimesMs: List<Long>? = null,
    val mushroomsPerLap: List<Int>? = null,
    /** Coins gained per lap, as mkwrs counts them. */
    val coinsPerLap: List<Int>? = null,
)

internal object AndroidBenchmarkCatalog {
    const val SOURCE_SHA256 = "${hash(benchmarkSource)}"
    private val entries = listOf(
${benchmarks.map((row) => `        AndroidTrackBenchmark(AndroidBenchmarkKind.${row.kind.toUpperCase()}, ${kotlinString(row.trackId)}, ${row.mode}, ${kotlinString(row.name)}, ${row.timeMs}L, ${row.countryId == null ? "null" : kotlinString(row.countryId)}${benchmarkExtras(row)})`).join(",\n")}
    )
    fun forTrack(trackId: String, mode: Int): List<AndroidTrackBenchmark> =
        entries.filter { it.trackId == trackId && it.mode == mode }

    fun forKind(kind: AndroidBenchmarkKind, mode: Int): List<AndroidTrackBenchmark> =
        entries.filter { it.kind == kind && it.mode == mode }
}
`;

writeFileSync(loadoutOutput, loadoutKotlin, "utf8");
writeFileSync(benchmarkOutput, benchmarkKotlin, "utf8");
