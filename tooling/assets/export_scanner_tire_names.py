"""Export the tire names of every game locale for the Web and Android scanners.

Both scanners read the printed tire name as second evidence beside the icon,
but their engine name table (`kart_config/names.json`, staged from the private
scanner assets) only carries British English and Dutch, so in the other ten
console languages a tire name could never match. Clean Assets carries the
names in all 13 locales; this exporter projects them, keyed by the engine's
tire index (Clean Assets `vehicleTires[].index`, 1:1 with names.json), into a
TypeScript module and a Java class. Names only, no images.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATABASE = ROOT.parent / "MK8DX Clean Assets - deploy" / "database.json"
DEFAULT_BASELINE = ROOT / "tooling" / "assets" / "schema9-release-baseline-v7.json"
DEFAULT_TS = ROOT / "apps" / "timetrials-scanner-web" / "src" / "engine" / "tireNames.generated.ts"
DEFAULT_JAVA = (ROOT / "apps" / "timetrials-android" / "scan-runtime" / "src" / "main" / "java" / "nl"
                / "mariokart8" / "mk8dxtimetrials" / "scanruntime" / "TireNameCatalog.java")
LOCALES = ("de-DE", "en-GB", "en-US", "es-ES", "fr-FR", "it-IT", "ja-JP", "ko-KR", "nl-NL",
           "pt-PT", "ru-RU", "zh-CN", "zh-TW")


class TireNameExportError(ValueError):
    pass


def checked_tires(database_path: Path, baseline_path: Path) -> tuple[list[tuple[int, dict]], str]:
    database_bytes = database_path.read_bytes()
    database_hash = hashlib.sha256(database_bytes).hexdigest()
    baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    if database_hash != baseline.get("database", {}).get("sha256"):
        raise TireNameExportError("database hash differs from baseline")
    tires = json.loads(database_bytes).get("collections", {}).get("vehicleTires")
    if not isinstance(tires, list) or not tires:
        raise TireNameExportError("tire collection is unavailable")
    out = []
    for position, tire in enumerate(tires):
        if tire.get("index") != position:
            raise TireNameExportError(f"tire index is not its position: {tire.get('id')}")
        names = tire.get("names") or {}
        missing = [loc for loc in LOCALES if not isinstance(names.get(loc), str) or not names[loc]]
        if missing:
            raise TireNameExportError(f"{tire.get('id')} lacks names for {missing}")
        out.append((position, {loc: names[loc] for loc in LOCALES}))
    return out, database_hash


def typescript_source(tires, database_hash: str) -> str:
    rows = "\n".join(
        f"  '{index}': Object.freeze({{ "
        + ", ".join(f"{json.dumps(loc)}: {json.dumps(name, ensure_ascii=False)}" for loc, name in names.items())
        + " }),"
        for index, names in tires)
    return f'''// Generated by tooling/assets/export_scanner_tire_names.py.
// Source database SHA-256: {database_hash}
// Tire names in every game locale, keyed by the engine's tire index.

export const TIRE_NAMES_SOURCE_DATABASE_SHA256 = '{database_hash}';

export const TIRE_NAMES: Readonly<Record<string, Readonly<Record<string, string>>>> = Object.freeze({{
{rows}
}});
'''


def java_source(tires, database_hash: str) -> str:
    def lit(text: str) -> str:
        return json.dumps(text, ensure_ascii=False)
    rows = "\n".join(
        f'        put(out, {index}, {", ".join(f"{lit(loc)}, {lit(name)}" for loc, name in names.items())});'
        for index, names in tires)
    return f'''// Generated by tooling/assets/export_scanner_tire_names.py.
// Source database SHA-256: {database_hash}
package nl.mariokart8.mk8dxtimetrials.scanruntime;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

/** Tire names in every game locale, keyed "index#locale" like the engine's vocabularies. */
public final class TireNameCatalog {{
    public static final String SOURCE_DATABASE_SHA256 = "{database_hash}";
    private static final Map<String, String> VOCAB = build();

    private TireNameCatalog() {{
    }}

    public static Map<String, String> vocab() {{
        return VOCAB;
    }}

    private static void put(Map<String, String> out, int index, String... pairs) {{
        for (int i = 0; i + 1 < pairs.length; i += 2) {{
            out.put(index + "#" + pairs[i], pairs[i + 1]);
        }}
    }}

    private static Map<String, String> build() {{
        Map<String, String> out = new LinkedHashMap<>();
{rows}
        return Collections.unmodifiableMap(out);
    }}
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description="Export scanner tire names for all game locales.")
    parser.add_argument("--database", type=Path, default=DEFAULT_DATABASE)
    parser.add_argument("--baseline", type=Path, default=DEFAULT_BASELINE)
    parser.add_argument("--ts-output", type=Path, default=DEFAULT_TS)
    parser.add_argument("--java-output", type=Path, default=DEFAULT_JAVA)
    arguments = parser.parse_args()
    tires, database_hash = checked_tires(arguments.database.resolve(), arguments.baseline.resolve())
    for path, text in ((arguments.ts_output, typescript_source(tires, database_hash)),
                       (arguments.java_output, java_source(tires, database_hash))):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
