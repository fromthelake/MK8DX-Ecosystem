from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

try:
    from .export_android_track_catalog import (
        DEFAULT_BASELINE,
        DEFAULT_CATALOG,
        DEFAULT_DATABASE,
        _checked_tracks,
        _load_object,
    )
except ImportError:  # Direct script execution.
    from export_android_track_catalog import (  # type: ignore[no-redef]
        DEFAULT_BASELINE,
        DEFAULT_CATALOG,
        DEFAULT_DATABASE,
        _checked_tracks,
        _load_object,
    )


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = (
    ROOT / "apps" / "timetrials-web" / "src" / "schema9-track-catalog.ts"
)


def export_typescript_source(
    database_path: Path,
    baseline_path: Path,
    catalog_path: Path,
) -> str:
    database, database_bytes = _load_object(database_path)
    baseline, _ = _load_object(baseline_path)
    catalog, catalog_bytes = _load_object(catalog_path)
    tracks, database_hash = _checked_tracks(
        database,
        database_bytes,
        baseline,
        catalog,
    )
    records = "\n".join(
        "    Object.freeze({ id: "
        f"{json.dumps(track['id'], ensure_ascii=False)}, index: {track['index']}, "
        f"displayName: {json.dumps(track['displayName'], ensure_ascii=False)}, "
        f"lapCount: {track['lapCount']} }}),"
        for track in tracks
    )
    catalog_hash = hashlib.sha256(catalog_bytes).hexdigest()
    return f'''// Generated by tooling/assets/export_web_track_catalog.py.
// Source database SHA-256: {database_hash}
// Source catalog SHA-256: {catalog_hash}

export type WebTrackCatalogEntry = Readonly<{{
  id: string;
  index: number;
  displayName: string;
  lapCount: 3 | 7;
}}>;

export const WEB_TRACK_COUNT = {len(tracks)};
export const WEB_TRACK_SOURCE_DATABASE_SHA256 = "{database_hash}";
export const WEB_TRACK_SOURCE_CATALOG_SHA256 = "{catalog_hash}";

export const schema9WebTrackCatalog: readonly WebTrackCatalogEntry[] =
  Object.freeze([
{records}
  ]);

const tracksById = new Map(
  schema9WebTrackCatalog.map((track) => [track.id, track]),
);

export function findSchema9WebTrack(
  trackId: string,
): WebTrackCatalogEntry | undefined {{
  return tracksById.get(trackId);
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Export the schema-9 web track catalog."
    )
    parser.add_argument("--database", type=Path, default=DEFAULT_DATABASE)
    parser.add_argument("--baseline", type=Path, default=DEFAULT_BASELINE)
    parser.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args()
    output = export_typescript_source(
        arguments.database.resolve(),
        arguments.baseline.resolve(),
        arguments.catalog.resolve(),
    )
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(output, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
