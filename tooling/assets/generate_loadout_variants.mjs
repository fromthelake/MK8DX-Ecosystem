#!/usr/bin/env node
// Generates presentation-only color-family metadata from the preserved Icon
// Matcher references. The referenced PNGs remain owner-private and are staged
// separately; stable IDs and matching semantics are safe production source.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const arg = (name) => { const i = process.argv.indexOf(name); if (i < 0 || !process.argv[i + 1]) throw new Error(`missing ${name}`); return process.argv[i + 1]; };
const manifest = JSON.parse(readFileSync(arg("--manifest"), "utf8"));
const pack = JSON.parse(readFileSync(arg("--pack"), "utf8"));
const characterMenuDirectory = arg("--character-menu-directory");
const characterMenuByIndex = new Map(readdirSync(characterMenuDirectory).flatMap((name) => {
  const match = /^(\d{3})_.*\.png$/.exec(name);
  return match ? [[Number(match[1]), `images/characters/menu/${name}`]] : [];
}));
const parse = (id, kind) => {
  const match = new RegExp(`^${kind}_variant\\.([a-z0-9_]+)\\.(\\d{3})_(.+)$`).exec(id);
  if (!match) throw new Error(`invalid variant id ${id}`);
  const color = match[3];
  const order = Number(match[2]);
  const iconPath = kind === "character"
    ? characterMenuByIndex.get(order)
    : `images/${kind === "body" ? "vehicles/bodies" : "vehicles/gliders"}/variants/${id}.png`;
  if (iconPath === undefined) throw new Error(`no Clean Assets menu icon for ${id}`);
  return { id, baseId: `${kind}.${match[1]}`, colorFamily: color, name: color.replaceAll("_", " ").replace(/\b\w/g, (c) => c.toUpperCase()), order, iconPath };
};
const characters = manifest.characters.filter((id) => id.startsWith("character_variant.")).map((id) => parse(id, "character"));
const bodies = manifest.bodies.filter((id) => id.startsWith("body_variant.")).map((id) => parse(id, "body"));
const gliders = manifest.gliders.filter((id) => id.startsWith("glider_variant.")).map((id) => parse(id, "glider"));
if (typeof pack.char_to_parts !== "object" || pack.char_to_parts === null || Array.isArray(pack.char_to_parts)) {
  throw new Error("pack has no character-to-parts mapping");
}
const allowedBodies = new Set(manifest.bodies);
const allowedGliders = new Set(manifest.gliders);
const characterParts = {};
for (const characterId of manifest.characters) {
  const source = pack.char_to_parts[characterId];
  if (typeof source !== "object" || source === null || Array.isArray(source)) {
    throw new Error(`pack has no loadout mapping for ${characterId}`);
  }
  const mapped = {};
  for (const [kind, allowed] of [["bodies", allowedBodies], ["gliders", allowedGliders]]) {
    const entries = source[kind] ?? {};
    if (typeof entries !== "object" || entries === null || Array.isArray(entries)) {
      throw new Error(`invalid ${kind} mapping for ${characterId}`);
    }
    for (const [partId, variantId] of Object.entries(entries)) {
      if (!allowed.has(partId) || typeof variantId !== "string") {
        throw new Error(`unknown ${kind} mapping ${characterId}/${partId}/${variantId}`);
      }
      let canonicalVariantId = variantId;
      if (!allowed.has(canonicalVariantId)) {
        const identity = /^(body|glider)_variant\.([a-z0-9_]+)\.(\d{3})_/.exec(variantId);
        const prefix = identity === null
          ? null
          : `${identity[1]}_variant.${identity[2]}.${identity[3]}_`;
        const candidates = prefix === null
          ? []
          : [...allowed].filter((id) => id.startsWith(prefix));
        if (candidates.length !== 1) {
          throw new Error(`unknown ${kind} mapping ${characterId}/${partId}/${variantId}`);
        }
        canonicalVariantId = candidates[0];
      }
      mapped[partId] = canonicalVariantId;
    }
  }
  characterParts[characterId] = mapped;
}
const unmigratedCharacterMappings = Object.keys(pack.char_to_parts)
  .filter((characterId) => !manifest.characters.includes(characterId));
if (unmigratedCharacterMappings.some((characterId) =>
  !["character.mii_medium", "character.mii_light", "character.mii_heavy"].includes(characterId))) {
  throw new Error("pack character mapping differs from the manifest character set");
}
const themes = {
  "character.luigi":"green","character.peach":"pink","character.daisy":"daisy","character.rosalina":"rosalina",
  "character.tanooki_mario":"mario_tan","character.cat_peach":"peach_cat","character.gold_mario":"mario_gold",
  "character.pink_gold_peach":"peach_gold","character.donkey_kong":"dk","character.dry_bones":"drybones",
  "character.dry_bowser":"bowser_dry","character.bowser_jr":"bowser_jr","character.king_boo":"kingboo",
  "character.koopa_troopa":"koopa","character.shy_guy":"shyguy","character.inkling_girl":"inkling_f",
  "character.inkling_boy":"inkling_m","character.villager_male":"villager_m","character.villager_female":"villager_f",
};
const ts = `// GENERATED by tooling/assets/generate_loadout_variants.mjs.\nexport type LoadoutVariant = Readonly<{ id:string; baseId:string; colorFamily:string; name:string; order:number; iconPath:string }>;\n` +
  `export const CHARACTER_COLOR_VARIANTS: readonly LoadoutVariant[] = ${JSON.stringify(characters, null, 1)};\n` +
  `export const BODY_COLOR_VARIANTS: readonly LoadoutVariant[] = ${JSON.stringify(bodies, null, 1)};\n` +
  `export const GLIDER_COLOR_VARIANTS: readonly LoadoutVariant[] = ${JSON.stringify(gliders, null, 1)};\n` +
  `export const CHARACTER_LOADOUT_VARIANTS: Readonly<Record<string,Readonly<Record<string,string>>>> = ${JSON.stringify(characterParts, null, 1)};\n` +
  `const CHARACTER_THEMES: Readonly<Record<string,string>> = ${JSON.stringify(themes, null, 1)};\n` +
  `const normalized=(value:string)=>value.replaceAll("_","").toLowerCase();\n` +
  `export function characterColorFamily(characterId:string):string|null { const variant=CHARACTER_COLOR_VARIANTS.find(v=>v.id===characterId); return variant?.colorFamily ?? CHARACTER_THEMES[characterId] ?? null; }\n` +
  `export function matchedLoadoutVariant(partId:string, characterId:string):LoadoutVariant|undefined { const list=partId.startsWith("body.")?BODY_COLOR_VARIANTS:partId.startsWith("glider.")?GLIDER_COLOR_VARIANTS:[]; const exact=CHARACTER_LOADOUT_VARIANTS[characterId]?.[partId]; if(exact!==undefined)return list.find(v=>v.id===exact); const family=characterColorFamily(characterId); if(!family)return undefined; return list.find(v=>v.baseId===partId&&normalized(v.colorFamily)===normalized(family)); }\n` +
  `export function loadoutVariantById(id:string|undefined):LoadoutVariant|undefined { return id===undefined?undefined:[...CHARACTER_COLOR_VARIANTS,...BODY_COLOR_VARIANTS,...GLIDER_COLOR_VARIANTS].find(v=>v.id===id); }\n`;
writeFileSync(arg("--web-output"), ts);
const kString = (v) => JSON.stringify(v);
const rows = (values) => values.map((v) => `        AndroidLoadoutVariant(${[v.id,v.baseId,v.colorFamily,v.name].map(kString).join(", ")}, ${v.order}, ${kString(v.iconPath)})`).join(",\n");
const mappedRows = Object.entries(characterParts).map(([characterId, parts]) =>
  `        ${kString(characterId)} to mapOf(${Object.entries(parts).map(([partId, variantId]) => `${kString(partId)} to ${kString(variantId)}`).join(", ")})`,
).join(",\n");
const kt = `// GENERATED by tooling/assets/generate_loadout_variants.mjs.\npackage nl.mariokart8.mk8dxtimetrials.builds\n\ninternal data class AndroidLoadoutVariant(val id:String,val baseId:String,val colorFamily:String,val name:String,val order:Int,val webIconPath:String){ val assetPath:String get()=if(id.startsWith("character_variant.")) "private-product/img/character/"+order+".png" else "private-product/img/variants/"+id+".png" }\ninternal object AndroidLoadoutVariants {\n    val characters=listOf(\n${rows(characters)}\n    )\n    val bodies=listOf(\n${rows(bodies)}\n    )\n    val gliders=listOf(\n${rows(gliders)}\n    )\n    private val themes=mapOf(\n${Object.entries(themes).map(([k,v])=>`        ${kString(k)} to ${kString(v)}`).join(",\n")}\n    )\n    private fun normalized(value:String)=value.replace("_","").lowercase()\n    fun characterColorFamily(id:String):String?=characters.firstOrNull{it.id==id}?.colorFamily?:themes[id]\n    fun matched(partId:String,characterId:String):AndroidLoadoutVariant? { val family=characterColorFamily(characterId)?:return null; val list=when{partId.startsWith("body.")->bodies;partId.startsWith("glider.")->gliders;else->emptyList()};return list.firstOrNull{it.baseId==partId&&normalized(it.colorFamily)==normalized(family)} }\n    fun byId(id:String?)=(characters+bodies+gliders).firstOrNull{it.id==id}\n}\n`;
const mappedKt = kt
  .replace(
    "    private fun normalized(value:String)=value.replace(\"_\",\"\").lowercase()\n",
    `    private val characterParts=mapOf(\n${mappedRows}\n    )\n` +
      "    private fun normalized(value:String)=value.replace(\"_\",\"\").lowercase()\n",
  )
  .replace(
    "    fun matched(partId:String,characterId:String):AndroidLoadoutVariant? { val family=characterColorFamily(characterId)?:return null; val list=when{partId.startsWith(\"body.\")->bodies;partId.startsWith(\"glider.\")->gliders;else->emptyList()};return list.firstOrNull{it.baseId==partId&&normalized(it.colorFamily)==normalized(family)} }\n",
    "    fun matched(partId:String,characterId:String):AndroidLoadoutVariant? { val list=when{partId.startsWith(\"body.\")->bodies;partId.startsWith(\"glider.\")->gliders;else->emptyList()}; characterParts[characterId]?.get(partId)?.let { exact -> return list.firstOrNull { it.id==exact } }; val family=characterColorFamily(characterId)?:return null;return list.firstOrNull{it.baseId==partId&&normalized(it.colorFamily)==normalized(family)} }\n",
  );
writeFileSync(arg("--android-output"), mappedKt.replace(
  "    fun byId(id:String?)=(characters+bodies+gliders).firstOrNull{it.id==id}\n",
  "    fun byId(id:String?)=(characters+bodies+gliders).firstOrNull{it.id==id}\n" +
  "    fun characterParts(base:List<AndroidBuildPart>):List<AndroidBuildPart> = (base + characters.mapNotNull { variant -> base.firstOrNull { it.id==variant.baseId }?.let { it.copy(sourceAssetIndex=variant.order,id=variant.id,name=it.name+\" · \"+variant.name,assetOverride=variant.assetPath) } }).sortedBy(AndroidBuildPart::sourceAssetIndex)\n",
));
const desktopIndex = process.argv.indexOf("--desktop-output");
if (desktopIndex >= 0) writeFileSync(process.argv[desktopIndex + 1], JSON.stringify({ characters, bodies, gliders, themes, characterParts }, null, 1));
console.log(`generated ${characters.length} character, ${bodies.length} body and ${gliders.length} glider variants`);
