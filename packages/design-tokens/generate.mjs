// Generates the platform adapters from the canonical token source (ADR-0207).
//
//   node packages/design-tokens/generate.mjs          write all adapters
//   node packages/design-tokens/generate.mjs --check  fail when an adapter is out of date
//
// Outputs (marked generated; never edit by hand):
//   apps/timetrials-web/styles/ds-tokens.css                         web CSS custom properties (--ds-*)
//   apps/timetrials-scanner-web/src/app/ds-tokens.generated.css      scanner subset (not yet wired, Phase 8)
//   apps/timetrials-android/.../ui/design/Mk8dxTokens.kt             Compose values
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
export const tokens = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
export const fonts = JSON.parse(readFileSync(join(here, "fonts.json"), "utf8"));
export const APPEARANCES = ["dark", "light", "hc"];

const get = (path) => path.split(".").reduce((node, key) => node?.[key], tokens.foundation) ??
  path.split(".").reduce((node, key) => node?.[key], tokens.semantic);
export function resolveRef(value) {
  if (typeof value !== "string" || !value.startsWith("{")) return value;
  const path = value.slice(1, -1);
  // semantic type references ("{type.display-2}") resolve inside semantic.type
  if (path.startsWith("type.")) return tokens.semantic.type[path.slice(5)];
  const found = get(path);
  if (found === undefined) throw new Error(`unresolved token reference ${value}`);
  return resolveRef(found);
}
export function color(name, appearance) {
  const entry = tokens.semantic.color[name];
  if (!entry) throw new Error(`unknown colour token ${name}`);
  return resolveRef(entry[appearance]);
}
const kebab = (name) => name.replace(/\./g, "-").replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
const camel = (name) => name.split(/[.\-]/).map((part, i) => i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)).join("")
  .replace(/^(\d)/, "n$1");
const HEADER_CSS = "/* GENERATED by packages/design-tokens/generate.mjs from tokens.json (ADR-0207). Do not edit. */\n";

// Adapter-only mapping of platform-independent elevation levels (the canonical source holds only levels).
const SHADOW = {
  dark: { 0: "none", 1: "0 1px 2px rgba(0,0,0,0.35)", 2: "0 10px 24px rgba(0,0,0,0.4)", 3: "0 22px 48px rgba(0,0,0,0.5)" },
  light: { 0: "none", 1: "0 1px 2px rgba(20,30,70,0.12)", 2: "0 10px 24px rgba(20,30,70,0.14)", 3: "0 22px 48px rgba(20,30,70,0.16)" },
  hc: { 0: "none", 1: "none", 2: "0 0 0 2px #FFFFFF", 3: "0 0 0 3px #FFFFFF" },
};

function colorBlock(appearance) {
  const lines = [];
  for (const name of Object.keys(tokens.semantic.color)) {
    lines.push(`  --ds-${kebab(name)}: ${color(name, appearance)};`);
  }
  lines.push(`  --ds-tint: ${tokens.semantic.tint[appearance]}%;`);
  for (const [name, level] of Object.entries(tokens.semantic.elevation)) {
    lines.push(`  --ds-elevation-${name}: ${SHADOW[appearance][resolveRef(level)]};`);
  }
  lines.push(`  --ds-focus-width: ${appearance === "hc" ? tokens.semantic.focus.widthHc : tokens.semantic.focus.width}px;`);
  lines.push(`  color-scheme: ${appearance === "light" ? "light" : "dark"};`);
  return lines.join("\n");
}

const rem = (px) => `${Number((px / 16).toFixed(4))}rem`;

export function webCss() {
  const s = tokens.semantic;
  const root = [];
  for (const [k, v] of Object.entries(s.spacing)) root.push(`  --ds-space-${k}: ${resolveRef(v)}px;`);
  for (const [k, v] of Object.entries(s.gutter)) root.push(`  --ds-gutter-${k}: ${v}px;`);
  root.push(`  --ds-container-max: ${s.container.max}px;`);
  for (const [k, v] of Object.entries(s.radius)) root.push(`  --ds-radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(s.slant)) root.push(`  --ds-slant-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(s.target)) root.push(`  --ds-target-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(s.motion)) root.push(`  --ds-motion-${k}: ${resolveRef(v)}ms;`);
  // Web adapter: the metric-matched local fallback face follows each self-hosted family (fonts.json).
  const withFallback = (stack) => stack.flatMap((f) => {
    const fallback = fonts.fallbacks.find((entry) => entry.for === f);
    return fallback === undefined ? [f] : [f, fallback.family];
  });
  for (const [k, v] of Object.entries(tokens.foundation.font.family)) root.push(`  --ds-font-${k}: ${withFallback(v).map((f) => /[\s-]/.test(f) && !/^(system-ui|sans-serif|monospace|ui-monospace|-apple-system)$/.test(f) ? `"${f}"` : f).join(", ")};`);
  for (const [k, t] of Object.entries(s.type)) {
    // rem, so the type follows the reader's text-size setting (DESIGN_SYSTEM §21 scaling).
    root.push(`  --ds-type-${k}-size: ${rem(t.size)};`);
    root.push(`  --ds-type-${k}-line: ${t.line};`);
    root.push(`  --ds-type-${k}-weight: ${t.weight};`);
    root.push(`  --ds-type-${k}-family: var(--ds-font-${t.family});`);
  }
  for (const [k, v] of Object.entries(tokens.component)) {
    if (typeof v === "number") root.push(`  --ds-${kebab(k)}: ${v}px;`);
  }
  const phone = Object.entries(s.type).filter(([, t]) => t.phone !== t.size).map(([k, t]) => `    --ds-type-${k}-size: ${rem(t.phone)};`);
  return HEADER_CSS +
    "@layer legacy, tokens, base, components;\n" +
    "@layer tokens {\n" +
    `:root {\n${root.join("\n")}\n}\n` +
    `:root, [data-appearance="dark"] {\n${colorBlock("dark")}\n}\n` +
    `[data-appearance="light"] {\n${colorBlock("light")}\n}\n` +
    `[data-appearance="hc"] {\n${colorBlock("hc")}\n}\n` +
    // The document appearance choice (ADR-0205). The boot script writes
    // data-appearance-choice on <html> before the stylesheets apply, and only
    // the *choice* is stored, so "system" is resolved here - per device, by
    // that device's own OS setting. A subtree naming its own data-appearance
    // (the gallery's side-by-side panels) still wins inside itself.
    `:root[data-appearance-choice="light"] {\n${colorBlock("light")}\n}\n` +
    `@media (prefers-color-scheme: light) {\n  :root[data-appearance-choice="system"] {\n${colorBlock("light").replace(/^/gm, "  ")}\n  }\n}\n` +
    `@media (prefers-contrast: more) {\n  :root:not([data-appearance]) {\n${colorBlock("hc").replace(/^/gm, "  ")}\n  }\n}\n` +
    `@media (max-width: ${s.breakpoint.tablet - 1}px) {\n  :root {\n${phone.join("\n")}\n  }\n}\n` +
    "}\n";
}

// @font-face for the self-hosted families (fonts.json, DESIGN_SYSTEM.md §3.1). Loaded only by pages
// that use design-system components; same origin, so the existing CSP (default-src 'self') covers it.
export function fontsCss() {
  const faces = fonts.faces.map((f) => `@font-face {
  font-family: "${f.family}";
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url("./${f.file}") format("woff2");
  unicode-range: ${f.unicodeRange};
}`);
  const local = (names) => names.map((n) => `local("${n}")`).join(", ");
  const fallbacks = fonts.fallbacks.flatMap((f) => {
    const metrics = `  size-adjust: ${f.sizeAdjust}%;
  ascent-override: ${f.ascentOverride}%;
  descent-override: ${f.descentOverride}%;
  line-gap-override: ${f.lineGapOverride}%;`;
    return [
      `@font-face {
  font-family: "${f.family}";
  font-weight: 100 ${f.boldFrom - 1};
  src: ${local(f.localRegular)};
${metrics}
}`,
      `@font-face {
  font-family: "${f.family}";
  font-weight: ${f.boldFrom} 900;
  src: ${local(f.localBold)};
${metrics}
}`,
    ];
  });
  return HEADER_CSS.replace("tokens.json", "fonts.json") + [...faces, ...fallbacks].join("\n") + "\n";
}

/**
 * The first-paint appearance boot script (ADR-0205 §3). It is a classic, blocking, same-origin
 * script in <head> before the stylesheets, because the product CSP is `script-src 'self'` with no
 * inline script and the page is a static index.html with no server templating. It must never throw:
 * storage can be blocked (private windows, cleared site data), in which case the device falls back
 * to System. The theme colours come from the token source, so this adapter holds no literals.
 */
export function appearanceBootJs() {
  const themeColor = (appearance) => color("surface.app", appearance);
  return "// GENERATED by packages/design-tokens/generate.mjs from tokens.json (ADR-0207). Do not edit.\n" +
`(function () {
  var html = document.documentElement;
  var choice = "system";
  var scale = 100;
  var motion = "system";
  try {
    var stored = JSON.parse(localStorage.getItem("mk8dx.appearance.v1") || "null");
    if (stored) {
      if (stored.choice === "light" || stored.choice === "dark" || stored.choice === "system") { choice = stored.choice; }
      if (stored.textScale === 115 || stored.textScale === 130) { scale = stored.textScale; }
      if (stored.reducedMotion === "on") { motion = "on"; }
    }
  } catch (error) { /* blocked storage: System, 100 %, OS motion */ }
  html.setAttribute("data-appearance-choice", choice);
  if (scale !== 100) { html.style.fontSize = scale + "%"; }
  if (motion === "on") { html.setAttribute("data-reduced-motion", "on"); }
  var light = choice === "light" || (choice === "system" &&
    typeof window.matchMedia === "function" && window.matchMedia("(prefers-color-scheme: light)").matches);
  var meta = document.querySelector('meta[name="theme-color"]');
  if (meta) { meta.setAttribute("content", light ? "${themeColor("light")}" : "${themeColor("dark")}"); }
})();
`;
}

export function scannerCss() {
  const lines = Object.keys(tokens.semantic.color).map((n) => `  --ds-${kebab(n)}: ${color(n, "dark")};`);
  return HEADER_CSS + "/* Scanner subset: colours for the dark camera UI. Wired into the scanner in Phase 8 (ADR-0206). */\n" +
    `:root {\n${lines.join("\n")}\n}\n`;
}

function exportImagePalette() {
  const source = tokens.component.exportImage;
  const resolved = (entries) => Object.fromEntries(Object.entries(entries)
    .map(([name, semantic]) => [name, color(semantic, "dark")]));
  return {
    colors: resolved(source.colors),
    tiers: resolved(source.tiers),
    seatPalettes: source.seatPalettes,
  };
}

/** Fixed-Dark renderer adapter for W35. The runtime imports no JSON and owns no colour literals. */
export function webExportImageTokens() {
  const palette = exportImagePalette();
  return `// GENERATED by packages/design-tokens/generate.mjs from tokens.json (ADR-0207, W35). Do not edit.\n` +
    `export const TOURNAMENT_EXPORT_TOKENS = ${JSON.stringify(palette, null, 2)} as const;\n`;
}

const kColor = (hexOrRgba) => {
  if (hexOrRgba.startsWith("rgba")) {
    const [r, g, b, a] = hexOrRgba.match(/[\d.]+/g).map(Number);
    const alpha = Math.round(a * 255).toString(16).padStart(2, "0").toUpperCase();
    return `Color(0x${alpha}${[r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("").toUpperCase()})`;
  }
  return `Color(0xFF${hexOrRgba.slice(1).toUpperCase()})`;
};
const kIntColor = (hexOrRgba) => {
  if (hexOrRgba.startsWith("rgba")) {
    const [r, g, b, a] = hexOrRgba.match(/[\d.]+/g).map(Number);
    const alpha = Math.round(a * 255).toString(16).padStart(2, "0").toUpperCase();
    return `0x${alpha}${[r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("").toUpperCase()}.toInt()`;
  }
  return `0xFF${hexOrRgba.slice(1).toUpperCase()}.toInt()`;
};
export function kotlin() {
  const names = Object.keys(tokens.semantic.color);
  const fields = names.map((n) => `    val ${camel(n)}: Color,`).join("\n");
  const inst = (ap) => names.map((n) => `        ${camel(n)} = ${kColor(color(n, ap))},`).join("\n");
  const s = tokens.semantic;
  const dp = (k, v) => `    val ${camel(k)} = ${v}.dp`;
  const type = Object.entries(s.type).map(([k, t]) =>
    `    val ${camel(k)} = Mk8dxTypeToken(family = Mk8dxFontRole.${t.family.charAt(0).toUpperCase() + t.family.slice(1)}, size = ${t.size}.sp, phoneSize = ${t.phone}.sp, lineHeight = ${t.line}f, weight = ${t.weight}, italic = ${t.italic === true}, caps = ${t.caps === true})`).join("\n");
  return `// GENERATED by packages/design-tokens/generate.mjs from tokens.json (ADR-0207). Do not edit.
package nl.mariokart8.mk8dxtimetrials.ui.design

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** Semantic colours for one appearance (DESIGN_SYSTEM.md §6). */
data class Mk8dxColorTokens(
${fields}
    /** Share (percent) of a semantic colour mixed into surfaceRaised for tinted chips. */
    val tintPercent: Int,
)

enum class Mk8dxFontRole { Display, Ui, Data }

data class Mk8dxTypeToken(
    val family: Mk8dxFontRole,
    val size: androidx.compose.ui.unit.TextUnit,
    val phoneSize: androidx.compose.ui.unit.TextUnit,
    val lineHeight: Float,
    val weight: Int,
    val italic: Boolean,
    val caps: Boolean,
)

object Mk8dxTokens {
    val Dark = Mk8dxColorTokens(
${inst("dark")}
        tintPercent = ${s.tint.dark},
    )
    val Light = Mk8dxColorTokens(
${inst("light")}
        tintPercent = ${s.tint.light},
    )
    val HighContrast = Mk8dxColorTokens(
${inst("hc")}
        tintPercent = ${s.tint.hc},
    )
}

object Mk8dxSpacing {
${Object.entries(s.spacing).map(([k, v]) => dp(k === "2xl" ? "xxl" : k === "3xl" ? "xxxl" : k === "4xl" ? "xxxxl" : k === "5xl" ? "xxxxxl" : k, resolveRef(v))).join("\n")}
    val gutterPhone = ${s.gutter.phone}.dp
    val gutterTablet = ${s.gutter.tablet}.dp
    val gutterDesktop = ${s.gutter.desktop}.dp
    val targetMin = ${s.target.min}.dp
    val targetMinDense = ${s.target.minDense}.dp
    val focusWidth = ${s.focus.width}.dp
    val focusWidthHighContrast = ${s.focus.widthHc}.dp
}

/** Platform mapping of the canonical elevation levels (overlay = 3, docked = 2, flat = 0). */
object Mk8dxElevation {
    val flat = 0.dp
    val docked = 6.dp
    val overlay = 12.dp
}

object Mk8dxMotion {
${Object.entries(s.motion).map(([k, v]) => `    const val ${camel(k)}Millis = ${resolveRef(v)}`).join("\n")}
}

object Mk8dxType {
${type}
}

object Mk8dxComponentDimensions {
${Object.entries(tokens.component).filter(([, v]) => typeof v === "number").map(([k, v]) => dp(k, v)).join("\n")}
}

/** Fixed-Dark W35 export palette; its Web twin is generated from the same token object. */
object Mk8dxExportImageTokens {
${Object.entries(exportImagePalette().colors).map(([name, value]) => `    val ${camel(name)} = ${kIntColor(value)}`).join("\n")}
    val tiers = mapOf(
${Object.entries(exportImagePalette().tiers).map(([name, value]) => `        "${name}" to ${kIntColor(value)},`).join("\n")}
    )
    val seatPalettes = listOf(
${exportImagePalette().seatPalettes.map((palette) => `        listOf(${palette.map(kIntColor).join(", ")}),`).join("\n")}
    )
}
`;
}

const outputs = [
  [join(repo, "apps/timetrials-web/styles/ds-tokens.css"), webCss],
  [join(repo, "apps/timetrials-web/styles/ds-fonts.css"), fontsCss],
  [join(repo, "apps/timetrials-web/styles/ds-appearance-boot.js"), appearanceBootJs],
  [join(repo, "apps/timetrials-scanner-web/src/app/ds-tokens.generated.css"), scannerCss],
  [join(repo, "apps/timetrials-web/src/tournament-export-tokens.generated.ts"), webExportImageTokens],
  [join(repo, "apps/timetrials-android/app/src/main/java/nl/mariokart8/mk8dxtimetrials/ui/design/Mk8dxTokens.kt"), kotlin],
];

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, make] of outputs) {
    const content = make();
    if (check) {
      let current = null; try { current = readFileSync(file, "utf8"); } catch { current = null; }
      if (current !== content) { console.error(`out of date: ${file}`); stale++; }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
      console.log("wrote", file.replace(repo + "\\", "").replace(repo + "/", ""));
    }
  }
  if (stale) process.exit(1);
}
